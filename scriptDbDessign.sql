create table public.hop_dong (
  ma_hop_dong bigint generated by default as identity primary key,
  ma_yeu_cau_thue bigint not null unique references public.yeu_cau_thue(ma_yeu_cau_thue) on delete restrict,
  ma_ho_so_khach_hang bigint not null references public.ho_so(ma_ho_so) on delete restrict,
  loai_muc_tieu varchar(20) not null,
  ma_phong bigint references public.phong(ma_phong) on delete set null,
  ma_giuong bigint references public.giuong(ma_giuong) on delete set null,
  ngay_vao_o date not null,
  gia_thue_co_ban_thang numeric(14,2) not null default 0 check (gia_thue_co_ban_thang >= 0),
