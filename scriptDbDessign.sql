  so_tien_da_thanh_toan numeric(14,2) not null default 0 check (so_tien_da_thanh_toan >= 0),
  ma_tai_khoan_ngan_hang varchar(100),
  ma_tham_chieu_qr varchar(100),
  ngay_lap date not null default current_date,
  ngay_den_han date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint chk_hoa_don_nguon check (
    ma_yeu_cau_thue is not null or ma_hop_dong is not null
  ),
  constraint chk_hoa_don_tien check (
    so_tien_da_thanh_toan <= tong_so_tien
